// Re-reads every recorded transaction from the chain and writes docs/guard/evidence-<network>.md:
// what each step did, the vault events it emitted (with refusal codes decoded), and explorer links.
import { writeFileSync } from 'node:fs';
import { decodeEventLog, formatEther } from 'viem';
import { NETWORKS } from '../networks.ts';
import { addrUrl, artifact, clients, loadRecord, testnetKey, txUrl, type NetworkName } from './lib.ts';

// argument: a record name in deployments/ (a network, or a network with a suffix such as lasna-v2)
const FILE = process.argv[2] ?? 'baseSepolia';
const NET = FILE.split('-')[0] as NetworkName;
const CODES = ['None', 'Frozen', 'Quarantined', 'UnknownPayee', 'LabelMismatch', 'OverCap', 'OverDailyLimit', 'Duplicate', 'TransferFailed'];
const rec = loadRecord(NET, FILE);
const { pub } = clients(NET, testnetKey('deployer'));
const ABIS = [artifact('GuardVault').abi, artifact('GuardReactive').abi];
const RULES = ['None', 'Burst', 'RepeatedRefusals', 'UnknownRecipient', 'CrossChainQuarantine', 'PayeeVeto', 'ScheduledPayment', 'Retry'];
const watchedAddr = String(rec.vault ?? rec.guard ?? '').toLowerCase();

const rows: string[] = [];
for (const t of rec.txs) {
  const r = await pub.getTransactionReceipt({ hash: t.hash });
  const what: string[] = [];
  for (const l of r.logs) {
    if (l.address.toLowerCase() !== watchedAddr) continue;
    for (const abi of ABIS) try {
      const e: any = decodeEventLog({ abi, data: l.data, topics: l.topics });
      if (e.eventName === 'PaymentRefused') what.push(`PaymentRefused (**${CODES[e.args.code]}**)`);
      else if (e.eventName === 'PaymentExecuted') what.push(`PaymentExecuted (${formatEther(e.args.amount)} ${NETWORKS[NET].currency})`);
      else if (e.eventName === 'Decision') what.push(`Decision (**${RULES[e.args.rule]}**)`);
      else what.push(e.eventName);
      break;
    } catch { /* try the next ABI */ }
  }
  rows.push(`| ${t.step} | ${r.status} | ${what.join(', ') || '-'} | [${t.hash.slice(0, 10)}…](${txUrl(NET, t.hash)}) |`);
}

const fmt = (n: number) => (n === 0 ? 'under 1 s (same second)' : `${n} s`);
const secs = (l: any) => l.originToCallbackSeconds != null ? fmt(l.originToCallbackSeconds) : l.reactiveToCallbackSeconds != null ? `${fmt(l.reactiveToCallbackSeconds)} from the CRON reaction` : '?';
const loops = (rec.loops ?? []).map((l: any) => `| ${l.name} | ${l.rule} | [origin](${txUrl(l.origin.chain, l.origin.tx)}) | [reactive](${txUrl(l.reactive.chain, l.reactive.tx)}) | ${l.callback.tx ? `[callback](${txUrl(l.callback.chain, l.callback.tx)})` : 'pending'} | ${secs(l)} |`);
const loopTable = loops.length ? `
## The full loop: origin -> reactive -> callback

| Scenario | Rule | Origin | Reactive (Lasna) | Callback | Origin → callback (block times) |
| --- | --- | --- | --- | --- | --- |
${loops.join('\n')}
` : '';
const md = `# Antibody Guard evidence: ${FILE} (chain ${NETWORKS[NET].chainId})

Generated by \`npm run evidence -- ${FILE}\` from the chain itself.

${rec.vault ? `- GuardVault: [\`${rec.vault}\`](${addrUrl(NET, rec.vault)})\n` : ''}${rec.guard ? `- GuardReactive: [\`${rec.guard}\`](${addrUrl(NET, rec.guard)})\n` : ''}- Owner (deployer): \`${rec.owner}\`
${rec.agent ? `- Agent: \`${rec.agent}\`\n` : ''}${rec.payees ? `- Payees: ${Object.entries(rec.payees).map(([k, v]) => `${k} \`${v}\``).join(', ')}\n` : ''}${loopTable}
| Step | Status | Vault events | Transaction |
| --- | --- | --- | --- |
${rows.join('\n')}
`;
writeFileSync(new URL(`../../docs/guard/evidence-${FILE}.md`, import.meta.url), md);
console.log(md);
