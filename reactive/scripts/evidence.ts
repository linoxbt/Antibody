// Re-reads every recorded transaction from the chain and writes docs/guard/evidence-<network>.md:
// what each step did, the vault events it emitted (with refusal codes decoded), and explorer links.
import { writeFileSync } from 'node:fs';
import { decodeEventLog, formatEther } from 'viem';
import { NETWORKS } from '../networks.ts';
import { addrUrl, artifact, clients, loadRecord, testnetKey, txUrl, type NetworkName } from './lib.ts';

const NET = (process.argv[2] ?? 'baseSepolia') as NetworkName;
const CODES = ['None', 'Frozen', 'Quarantined', 'UnknownPayee', 'LabelMismatch', 'OverCap', 'OverDailyLimit', 'Duplicate', 'TransferFailed'];
const rec = loadRecord(NET);
const { pub } = clients(NET, testnetKey('deployer'));
const { abi } = artifact('GuardVault');

const rows: string[] = [];
for (const t of rec.txs) {
  const r = await pub.getTransactionReceipt({ hash: t.hash });
  const what: string[] = [];
  for (const l of r.logs) {
    if (l.address.toLowerCase() !== String(rec.vault).toLowerCase()) continue;
    try {
      const e: any = decodeEventLog({ abi, data: l.data, topics: l.topics });
      if (e.eventName === 'PaymentRefused') what.push(`PaymentRefused (**${CODES[e.args.code]}**)`);
      else if (e.eventName === 'PaymentExecuted') what.push(`PaymentExecuted (${formatEther(e.args.amount)} ${NETWORKS[NET].currency})`);
      else what.push(e.eventName);
    } catch { /* not a vault event */ }
  }
  rows.push(`| ${t.step} | ${r.status} | ${what.join(', ') || '-'} | [${t.hash.slice(0, 10)}…](${txUrl(NET, t.hash)}) |`);
}

const md = `# Antibody Guard evidence: ${NET} (chain ${NETWORKS[NET].chainId})

Generated by \`npm run evidence -- ${NET}\` from the chain itself.

- GuardVault: [\`${rec.vault}\`](${addrUrl(NET, rec.vault)})
- Owner (deployer): \`${rec.owner}\`
- Agent: \`${rec.agent}\`
- Payees: ${Object.entries(rec.payees ?? {}).map(([k, v]) => `${k} \`${v}\``).join(', ')}

| Step | Status | Vault events | Transaction |
| --- | --- | --- | --- |
${rows.join('\n')}
`;
writeFileSync(new URL(`../../docs/guard/evidence-${NET}.md`, import.meta.url), md);
console.log(md);
