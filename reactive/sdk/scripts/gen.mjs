// Copy the contracts' ABIs (and the bytecode used to deploy them) from ../abi into src/generated.ts, so
// the SDK ships them with full types (as const) and needs nothing from the rest of the repository.
import { readFileSync, writeFileSync } from 'node:fs';
const abi = new URL('../../abi/', import.meta.url);
const read = (f) => JSON.parse(readFileSync(new URL(f, abi), 'utf8'));
const out = ['// Generated by scripts/gen.mjs from ../abi: do not edit.'];
for (const c of ['GuardVault', 'GuardMemory', 'GuardReactive', 'RiskOracle']) out.push(`export const ${c}Abi = ${JSON.stringify(read(`${c}.json`))} as const;`);
for (const c of ['GuardVault', 'GuardMemory']) out.push(`export const ${c}Bytecode = ${JSON.stringify(read(`${c}.code.json`).bytecode)} as \`0x\${string}\`;`);
writeFileSync(new URL('../src/generated.ts', import.meta.url), out.join('\n') + '\n');
